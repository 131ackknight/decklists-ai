/**
 * Writes PROGRESS.md from the files, never by hand (2026-11-07, owner: "We arent
 * very careful with our data are we?").
 *
 *   pnpm exec tsx scripts/scoreboard.ts
 *
 * Sources, all in the repo: the run register (evals/runs.jsonl), the result files
 * it points to, the frozen tests (evals/tests.ts), the owner's exported answers
 * (evals/answers/), and evals/progress-log-only.md, the one hand-kept part, for
 * numbers that exist only in BUILD_LOG.md. Rerun it after every run or judging
 * round; it changes nothing else.
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { loadCardIndex } from "../src/cards/load";
import { FileDataSource } from "../src/data/source";
import { pages, pairVerdicts, playVerdicts, ratingRows } from "../evals/answers";
import { latestRuns, readRegister, type RunRecord } from "../evals/register";
import { round4Items, toCounts, type Line } from "../evals/round4/items";
import { PROTOCOL, pairedGain } from "../evals/protocol";
import { futureLists, inventorGems, loadLists, overlap, settledLists, settledScore, shareScore, type Counts } from "../evals/score";
import { TESTS, testById } from "../evals/tests";

const index = loadCardIndex();
const items = new Map(round4Items(index).map((it) => [it.id, it]));
const runs = latestRuns().finished;
const resultsOf = (r: RunRecord) => JSON.parse(readFileSync(r.file, "utf8")) as Record<string, unknown> & { results: Record<string, unknown>[] };
const decksOf = (r: RunRecord) => new Map(resultsOf(r).results.filter(Boolean).map((x) => [x.id as string, (x.deck as { main: Line[] } | null) ?? null]));
const one = (x: number) => x.toFixed(1);
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const versionNo = (h?: string) => Number(h?.replace(/\D/g, "") || 0);
const modelName = (m?: string) => (m ?? "").replace("claude-", "").replace(/-(\d)-(\d)$/, " $1.$2").replace(/^./, (c) => c.toUpperCase());

async function main() {
  const out: string[] = [];
  const commit = execSync("git rev-parse --short HEAD").toString().trim();
  out.push(
    "# decklists.ai progress",
    "",
    `Generated by \`scripts/scoreboard.ts\` on ${new Date().toLocaleDateString("en-CA")} at commit ${commit}. **Don't edit this file**: rerun the script. Every number in sections 1-6 is computed from the repo's files: the run register (\`evals/runs.jsonl\`), the result files, the frozen tests (\`evals/tests.ts\`) and the owner's exported answers (\`evals/answers/\`). Section 7 is the only hand-kept part: numbers that exist only in BUILD_LOG.md. "not run" = no run in the register.`,
    "",
  );

  // 1. The frozen tests.
  out.push("## 1. The tests (frozen; `evals/tests.ts`)", "");
  out.push(table(["Test", "Kind", "Items", "What it measures", "Fingerprint"], TESTS.map((t) => [t.id, t.kind, t.items.length, t.what, `\`${t.frozen}\``])), "");

  // 2. Automatic scores.
  const through = String(testById("tuning-v1").params.dataThrough);
  const lists = loadLists(through);
  const history = await FileDataSource.load("data/reference-lists-all.jsonl", index);
  const settledFor = (testId: string, from: number, to: number) =>
    new Map(testById(testId).items.map((id) => [id, settledLists(index, lists, items.get(id)!.target!, from, to)] as const));
  const holdout = settledFor("holdout-v1", 30, 90);
  const post = settledFor("post-v1", 7, 365);
  const future = settledFor("future-v1", 7, 365);
  const tuning = new Map(testById("tuning-v1").items.map((id) => [id, futureLists(index, lists, items.get(id)!.target!)] as const));
  const gems = new Map(testById("brewing-v1").items.map((id) => [id, inventorGems(index, history, items.get(id)!, tuning.get(id)!.firstWeek)] as const));

  /** The best list that existed before each deck appeared, picked with hindsight against what it became. */
  const counted = new Map<(typeof lists)[number], Counts>();
  const countsOf = (l: (typeof lists)[number]) => counted.get(l) ?? counted.set(l, toCounts(index, l.main)).get(l)!;
  const hindsight = (settled: Map<string, Counts[]>) => {
    const per = [...settled].map(([id, s]) => {
      const t = items.get(id)!.target!;
      const prior = lists.filter((l) => l.format === t.format && Date.parse(l.date) < Date.parse(t.firstSeen));
      return prior.reduce((b, l) => Math.max(b, settledScore(countsOf(l), s)), 0);
    });
    return per.reduce((a, b) => a + b, 0) / per.length;
  };
  const settledMean = (decks: Map<string, { main: Line[] } | null>, settled: Map<string, Counts[]>) => {
    const vals = [...settled].flatMap(([id, s]) => (decks.get(id) ? [settledScore(toCounts(index, decks.get(id)!.main), s)] : []));
    return vals.length === settled.size ? one(vals.reduce((a, b) => a + b, 0) / vals.length) : `${one(vals.reduce((a, b) => a + b, 0) / Math.max(1, vals.length))} (${vals.length} decks)`;
  };
  const tuneBrew = (decks: Map<string, { main: Line[] } | null>) => {
    const tune: number[] = [];
    const brew: number[] = [];
    let found = 0;
    let of = 0;
    for (const [id, f] of tuning) {
      const d = decks.get(id);
      if (!d) continue;
      const deck = toCounts(index, d.main);
      tune.push(shareScore(index, deck, f.settled).all);
      if (gems.has(id)) {
        brew.push(shareScore(index, deck, f.firstWeek).all);
        found += gems.get(id)!.filter((g) => deck.has(g)).length;
        of += gems.get(id)!.length;
      }
    }
    const mean = (xs: number[]) => one((xs.reduce((a, b) => a + b, 0) / xs.length) * 100);
    return { tune: mean(tune), brew: mean(brew), gems: `${found}/${of}` };
  };

  type Cell = Record<string, string[]>;
  const byVersion = new Map<string, { harness?: string; model?: string; cells: Cell; cost: number[] }>();
  // Run 1 before run 2 (by the file's -r2 tag), then by date.
  const runNo = (f: string) => Number(f.match(/-r(\d+)(?:-partial)?\.json$/)?.[1] ?? 1);
  const scored = runs
    .filter((r) => r.tests.some((t) => ["holdout-v1", "post-v1", "future-v1", "tuning-v1", "brewing-v1", "panel-v1"].includes(t)))
    .sort((a, b) => runNo(a.file) - runNo(b.file) || a.at.localeCompare(b.at));
  for (const r of scored) {
    const key = `${r.harness} ${r.model}`;
    const v = byVersion.get(key) ?? { harness: r.harness, model: r.model, cells: {}, cost: [] };
    const decks = decksOf(r);
    const add = (col: string, val: string) => (v.cells[col] = [...(v.cells[col] ?? []), val]);
    if (r.tests.includes("holdout-v1")) add("holdout-v1", settledMean(decks, holdout));
    if (r.tests.includes("post-v1")) add("post-v1", settledMean(decks, post));
    if (r.tests.includes("future-v1")) add("future-v1", settledMean(decks, future));
    if (r.tests.includes("tuning-v1")) {
      const s = tuneBrew(decks);
      add("tuning-v1", s.tune);
      add("brewing-v1", s.brew);
      add("gems", s.gems);
    }
    if (r.costUsd !== undefined) v.cost.push(r.costUsd / r.items);
    byVersion.set(key, v);
  }
  const cols = ["holdout-v1", "post-v1", "future-v1", "tuning-v1", "brewing-v1", "gems"];
  const costRange = (c: number[]) => {
    if (!c.length) return "not recorded";
    const [lo, hi] = [Math.min(...c).toFixed(2), Math.max(...c).toFixed(2)];
    return `$${lo}${hi !== lo ? `-${hi}` : ""} (${c.length} run${c.length > 1 ? "s" : ""})`;
  };
  const rows: (string | number)[][] = [
    ["Closest earlier list, picked with hindsight", one(hindsight(holdout)), one(hindsight(post)), one(hindsight(future)), "", "", "", ""],
    ...[...byVersion.values()]
      .sort((a, b) => versionNo(a.harness) - versionNo(b.harness) || (a.model ?? "").localeCompare(b.model ?? ""))
      .map((v) => [`${v.harness}${v.model === "claude-opus-5-5" ? "" : `, ${modelName(v.model)}`}`, ...cols.map((c) => v.cells[c]?.join(" / ") ?? "not run"), costRange(v.cost)]),
  ];
  const listed = new Set([...byVersion.values()].map((v) => v.harness));
  const unlisted = [...new Set(runs.map((r) => r.harness).filter((h): h is string => !!h && !listed.has(h)))].sort((a, b) => versionNo(a) - versionNo(b));
  out.push("## 2. Automatic scores (match % with real decks, Opus 5.5 unless named)", "");
  out.push(table(["Version", "holdout-v1", "post-v1", "future-v1", "tuning-v1", "brewing-v1", "Gems found", "Cost per deck"], rows), "");
  out.push(`"a / b / c" = run 1 / run 2 / run 3 (by the file's run tag). Cost per deck: the range over this version's runs above (recorded cost / items), panel runs included. Versions with runs in the register but none on these tests: ${unlisted.join(", ") || "none"}.`, "");

  // 2b. Candidates against the base, by the frozen protocol.
  /** One run's score on each deck of a test. */
  const deckScores = (r: RunRecord, testId: string): Map<string, number> => {
    const decks = decksOf(r);
    const m = new Map<string, number>();
    const settled = testId === "holdout-v1" ? holdout : testId === "post-v1" ? post : testId === "future-v1" ? future : null;
    for (const id of testById(testId).items) {
      const d = decks.get(id);
      if (!d) continue;
      const deck = toCounts(index, d.main);
      if (settled) m.set(id, settledScore(deck, settled.get(id)!));
      else if (testId === "tuning-v1") m.set(id, shareScore(index, deck, tuning.get(id)!.settled).all * 100);
      else if (testId === "brewing-v1" && gems.has(id)) m.set(id, shareScore(index, deck, tuning.get(id)!.firstWeek).all * 100);
    }
    return m;
  };
  // Only runs made on the protocol's data count: recorded fingerprints, or for older runs, finishing after the file last changed.
  const onProtocolData = (r: RunRecord) =>
    r.data ? r.data.history === PROTOCOL.data.history.sha256 && r.data.recent === PROTOCOL.data.recent.sha256 : r.at >= PROTOCOL.data.history.since;
  const allRunsOf = (harness: string, testId: string) => scored.filter((r) => r.harness === harness && r.model === PROTOCOL.model && r.tests.includes(testId));
  const runsOf = (harness: string, testId: string) => allRunsOf(harness, testId).filter(onProtocolData);
  const earlierData = (harness: string, testId: string) => allRunsOf(harness, testId).length - runsOf(harness, testId).length;
  const signed = (x: number) => `${x >= 0 ? "+" : ""}${one(x)}`;
  const gainOf = (cand: RunRecord[], base: RunRecord[], testId: string, harness: string) => {
    const older = earlierData(harness, testId);
    const note = older ? ` (${older} more on an earlier data copy, not counted)` : "";
    if (!cand.length || !base.length) return { text: `${older ? "none on the protocol's data" : "not run"}${note}`, g: null as ReturnType<typeof pairedGain> | null };
    const g = pairedGain(cand.map((r) => deckScores(r, testId)), base.map((r) => deckScores(r, testId)));
    return { text: `${signed(g.gain)} (${signed(g.lo)} to ${signed(g.hi)}), ${cand.length} run${cand.length > 1 ? "s" : ""}${note}`, g };
  };
  const baseDev = runsOf(PROTOCOL.base, PROTOCOL.dev);
  const baseTest = PROTOCOL.test.map((t) => runsOf(PROTOCOL.base, t));
  const candidates = [
    ...new Set(scored.filter((r) => r.model === PROTOCOL.model && r.harness !== PROTOCOL.base && r.tests.some((t) => t === PROTOCOL.dev || PROTOCOL.test.includes(t))).map((r) => r.harness!)),
  ].sort((a, b) => versionNo(a) - versionNo(b));
  const verdictRows = candidates.map((h) => {
    const devRuns = runsOf(h, PROTOCOL.dev);
    const dev = gainOf(devRuns, baseDev, PROTOCOL.dev, h);
    const tests = PROTOCOL.test.map((t, i) => gainOf(runsOf(h, t), baseTest[i], t, h));
    const short = [PROTOCOL.devRuns - devRuns.length, PROTOCOL.devRuns - baseDev.length];
    let verdict: string;
    if (!dev.g) verdict = "no dev runs";
    else if (short[0] > 0 || short[1] > 0) verdict = `no verdict yet: needs ${[short[0] > 0 ? `${short[0]} more dev run(s)` : "", short[1] > 0 ? `${short[1]} more base run(s)` : ""].filter(Boolean).join(" and ")}`;
    else if (dev.g.lo <= 0) verdict = "dropped: no clear dev gain";
    else if (PROTOCOL.test.some((t, i) => runsOf(h, t).length < PROTOCOL.testRuns || baseTest[i].length < PROTOCOL.testRuns)) verdict = "dev win: confirm on test";
    else verdict = tests.every((t) => t.g!.hi > 0) ? "**kept**" : "dropped: worse on test";
    return [h, dev.text, ...tests.map((t) => t.text), verdict];
  });
  out.push(`### 2b. Candidates vs the base (${PROTOCOL.id}, \`evals/protocol.ts\`)`, "");
  out.push(
    `Base: ${PROTOCOL.base}, with ${baseDev.length} run(s) on dev (${PROTOCOL.dev}) and ${baseTest.map((r, i) => `${r.length} on ${PROTOCOL.test[i]}`).join(", ")}. Gain = points over the base, paired by deck, with its 95% range. Only runs on the protocol's data count (\`${PROTOCOL.data.history.file}\` ${PROTOCOL.data.history.sha256}, \`${PROTOCOL.data.recent.file}\` ${PROTOCOL.data.recent.sha256}). Rule: ${PROTOCOL.rule}`,
    "",
  );
  out.push(table(["Candidate", `Dev: ${PROTOCOL.dev}`, ...PROTOCOL.test.map((t) => `Test: ${t}`), "Verdict"], verdictRows), "");

  // 3. The owner's judging rounds.
  out.push("## 3. The owner's judging rounds (`evals/answers/`)", "");
  const roundRows: (string | number)[][] = [];
  // Later scorecards also report the prompts the first one covered: the comparison BUILD_LOG.md made on
  // 10-14, before two answers were excluded, so both ways are shown.
  const firstRatings = pages().find((p) => p.kind === "ratings" && p.answers && p.key);
  const firstPrompts = new Set(firstRatings ? Object.values(JSON.parse(readFileSync(firstRatings.key!, "utf8")) as Record<string, { prompt: string }>).map((k) => k.prompt) : []);
  for (const p of pages()) {
    let result = "";
    if (!p.answers) result = "no answers saved";
    else if (p.kind === "ratings") {
      const rs = ratingRows(p.slug);
      const all = ratingRows(p.slug, { includeExcluded: true });
      const labels = [...new Set(rs.map((r) => r.label!))].sort();
      const mean = (xs: { mean: number }[]) => (xs.reduce((a, r) => a + r.mean, 0) / xs.length).toFixed(2);
      result = labels
        .map((l) => {
          const mine = rs.filter((r) => r.label === l);
          if (p === firstRatings || mine.every((r) => firstPrompts.has(r.prompt))) return `${l} ${mean(mine)}`;
          const shared = mine.filter((r) => firstPrompts.has(r.prompt));
          const sharedAll = all.filter((r) => r.label === l && firstPrompts.has(r.prompt));
          const extra = sharedAll.length > shared.length ? `; ${mean(sharedAll)} counting the ${sharedAll.length - shared.length} later-excluded answer(s)` : "";
          return `${l} ${mean(mine)} (on the ${firstPrompts.size} prompts of the ${firstRatings!.title}: ${mean(shared)}${extra})`;
        })
        .join("; ");
    } else if (p.kind === "pairs") {
      const vs = pairVerdicts(p.slug);
      const tally = new Map<string, { win: number; loss: number }>();
      let tie = 0;
      let neither = 0;
      for (const v of vs) {
        if (v.winner === "tie") tie++;
        else if (v.winner === "neither") neither++;
        else {
          const [w, l] = v.winner === "A" ? [v.left!, v.right!] : [v.right!, v.left!];
          tally.set(w, { win: (tally.get(w)?.win ?? 0) + 1, loss: tally.get(w)?.loss ?? 0 });
          tally.set(l, { win: tally.get(l)?.win ?? 0, loss: (tally.get(l)?.loss ?? 0) + 1 });
        }
      }
      result = `${[...tally].sort().map(([l, t]) => `${l} won ${t.win}, lost ${t.loss}`).join("; ")}; same ${tie}${neither ? `; neither ${neither}` : ""}`;
    } else {
      const vs = playVerdicts(p.slug);
      const harnesses = [...new Set(vs.map((v) => v.harness!))].sort((a, b) => versionNo(a) - versionNo(b));
      result = harnesses
        .map((h) => {
          const mine = vs.filter((v) => v.harness === h);
          const count = (x: string) => mine.filter((v) => v.play === x).length;
          return `${h}: yes ${count("yes")} of ${mine.length}${count("closer") ? `, closer ${count("closer")}` : ""}${count("further") ? `, further ${count("further")}` : ""}`;
        })
        .join("; ");
    }
    roundRows.push([p.logDate, `[${p.title}](${p.url})`, p.what, p.answers, result]);
  }
  out.push(table(["Log date", "Page", "Round", "Answers", "Result"], roundRows), "");
  out.push("Pairs pages: A is the key's left label, B its right; \"same\" is a tie. Ratings pages: mean of plan, legal, mana and shell per answer, averaged per set, complete ratings only and the key's excluded answers left out (as `scripts/analyze-ratings.ts`).", "");

  // 4. The blind panel, per prompt.
  out.push("## 4. Blind panel (panel-v1), per prompt", "");
  const panelPages = pages().filter((p) => p.what.startsWith("panel-v1"));
  const panelCols = panelPages.flatMap((p) => [...new Set(playVerdicts(p.slug).map((v) => v.harness!))].sort((a, b) => versionNo(a) - versionNo(b)).map((h) => ({ p, h })));
  const panelRows = testById("panel-v1").items.map((id) => [
    id.replace(/^expert\d-/, "").replace(/-/g, " "),
    ...panelCols.map(({ p, h }) => playVerdicts(p.slug).find((v) => v.item === id && v.harness === h)?.play ?? "not judged"),
  ]);
  const yes = panelCols.map(({ p, h }) => playVerdicts(p.slug).filter((v) => v.harness === h && v.play === "yes").length);
  out.push(table(["Prompt", ...panelCols.map(({ p, h }) => `${h} (${p.title.replace("Blind Panel ", "")})`)], [...panelRows, ["**Yes, of 17**", ...yes.map((y) => `**${y}**`)]]), "");

  // 5. Diagnostic tests.
  out.push("## 5. Tests of the AI's judgment and knowledge", "");
  const diag: (string | number)[][] = [];
  for (const r of runs.filter((x) => x.tests.some((t) => testById(t).kind === "diagnostic")).sort((a, b) => a.at.localeCompare(b.at))) {
    const d = resultsOf(r);
    const test = r.tests[0];
    let result = "";
    if (test === "gem-v1") result = `gem rated above a look-alike ${one((d.mean as number) * 100)}%`;
    else if (test === "picker-v1") result = `owner's yes picked ${d.right} of ${d.total}; picked "A" ${d.pickedA}`;
    else if (test.startsWith("taste")) result = `real deck picked ${d.inventor} of ${d.total}; picked "A" ${d.pickedA}`;
    else if (test === "playtest-v1") {
      const g = (x: string) => d.results.filter((y) => (y.grade as { found: string }).found === x).length;
      result = `in the file: yes ${g("yes")}, partly ${g("partly")}, no ${g("no")} (${d.results.length} decks)`;
    } else if (test === "found-squee-v1") {
      const found = toCounts(index, (JSON.parse(readFileSync(String(testById(test).params.list), "utf8")) as { main: Line[] }).main);
      result = d.results.map((x) => `${(x.id as string).endsWith("-a") ? "A" : "B"} ${overlap(found, toCounts(index, (x.deck as { main: Line[] }).main))}/60`).join(", ");
    }
    diag.push([r.at.slice(0, 10), test, r.file.replace("evals/results/round4/", ""), result, r.note ?? ""]);
  }
  out.push(table(["Date", "Test", "File", "Result", "Note"], diag), "");

  // 6. The register.
  const all = readRegister();
  const scripts = new Map<string, { n: number; cost: number; noCost: number }>();
  for (const r of runs) {
    const s = scripts.get(r.script) ?? { n: 0, cost: 0, noCost: 0 };
    s.n++;
    if (r.costUsd === undefined) s.noCost++;
    else s.cost += r.costUsd;
    scripts.set(r.script, s);
  }
  out.push("## 6. The run register (`evals/runs.jsonl`)", "");
  out.push(
    table(
      ["Script", "Runs", "Recorded cost", "Runs with no cost in the file"],
      [...[...scripts].sort((a, b) => b[1].cost - a[1].cost).map(([s, v]) => [s, v.n, `$${v.cost.toFixed(2)}`, v.noCost]), ["**All**", runs.length, `**$${runs.reduce((a, r) => a + (r.costUsd ?? 0), 0).toFixed(2)}**`, runs.filter((r) => r.costUsd === undefined).length]],
    ),
    "",
  );
  const unfinished = latestRuns().unfinished;
  out.push(
    `${all.filter((r) => r.backfilled).length} runs were backfilled from their result files on 2026-11-07 (code version unknown); ${all.filter((r) => !r.backfilled && r.event === "finished").length} have been recorded live since. Unfinished (started, never finished): ${unfinished.length ? unfinished.map((r) => r.file).join(", ") : "none"}. BUILD_LOG.md's running total is higher than the recorded cost because it also counts runs whose result files weren't kept and runs whose files store no cost.`,
    "",
  );

  // 7. The hand-kept part.
  out.push(readFileSync("evals/progress-log-only.md", "utf8").trim(), "");
  writeFileSync("PROGRESS.md", out.join("\n"));
  console.log(`wrote PROGRESS.md: ${scored.length} scored runs, ${pages().length} judging pages, ${diag.length} diagnostic runs`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
